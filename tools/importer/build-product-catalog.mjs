/**
 * Builds the product -> category folder map used by import-product-page.js,
 * and the list of source product page URLs to import.
 *
 * The four listing pages (/en/<category>-products) each show every product in
 * one content fragment folder; this reads the same data they render.
 *
 *   node tools/importer/build-product-catalog.mjs
 */
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const SOURCE = 'https://main--luma-site-14-08--livedemoservices.aem.live';
const PROXY = 'https://275323-918sangriatortoise.adobeioruntime.net/api/v1/web/dx-excshell-1/fetch-product-information';
const ENVIRONMENT = 'p104656-e2246865';
const FRAGMENT_ROOT = '/content/dam/luma3/en/fragments/luma-common-cf-products';
const CATEGORIES = ['women', 'men', 'gear', 'yoga'];

// same as toClassName() in scripts/aem.js, which the listing block uses to build links
const toSlug = (name) => name.toLowerCase().replace(/[^0-9a-z]/gi, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');

const here = dirname(fileURLToPath(import.meta.url));
const products = {};

for (const category of CATEGORIES) {
  const url = `${PROXY}?endpoint=productsListByPath&environment=${ENVIRONMENT}&_path=${FRAGMENT_ROOT}/${category}`;
  const json = await (await fetch(url)).json();
  const items = Object.values(json.data || {})[0]?.items || [];
  items.forEach((item) => {
    const sku = item.sku || item.id;
    if (!sku || products[sku]) return; // a SKU can appear twice in one folder
    products[sku] = {
      sku,
      name: item.name,
      folder: `${category}-products`,
      path: `/en/${category}-products/${toSlug(item.name)}`,
    };
  });
  console.log(`${category}: ${items.length} items`);
}

const paths = Object.values(products).map((p) => p.path);
const duplicates = paths.filter((p, i) => paths.indexOf(p) !== i);
if (duplicates.length) throw new Error(`Duplicate product page paths: ${duplicates.join(', ')}`);

writeFileSync(
  join(here, 'product-catalog.js'),
  `/* eslint-disable */\n// Generated by build-product-catalog.mjs - do not edit by hand.\nexport default ${JSON.stringify(products, null, 2)};\n`,
);
writeFileSync(
  join(here, 'urls-product-page.txt'),
  `${Object.keys(products).map((sku) => `${SOURCE}/en/product?productId=${encodeURIComponent(sku)}`).join('\n')}\n`,
);
console.log(`${Object.keys(products).length} products written`);
